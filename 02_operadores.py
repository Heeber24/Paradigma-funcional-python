#Operadores in Python

# Operadores Aritméticos
a = 10
b = 3
print("Suma:", a + b)          # Suma
print("Resta:", a - b)         # Resta
print("Multiplicación:", a * b) # Multiplicación
print("División:", a / b)       # División
print("Módulo:", a % b)         # Módulo (es el residuo de la división)
print("Exponente:", a ** b)     # Exponente (es a elevado a la b) 
print("División Entera:", a // b) # División Entera (es la parte entera de la división)
print()

# Operadores de Comparación
x = 5   
y = 10
print("Igualdad:", x == y)          # Igualdad
print("Desigualdad:", x != y)       # Desigualdad
print("Mayor que:", x > y)          # Mayor que
print("Menor que:", x < y)          # Menor que
print("Mayor o igual que:", x >= y) # Mayor o igual que
print("Menor o igual que:", x <= y) # Menor o igual que
print()

# Operadores Lógicos
p = True
q = False
print("AND:", p and q)  # AND (ambos deben ser True)
print("OR:", p or q)    # OR (al menos uno debe ser True)
print("NOT p:", not p)  # NOT (negación de p)
print("NOT q:", not q)  # NOT (negación de q)
print()

# Operadores de Asignación (una forma abreviada y práctica de asignar valores)
c = 15
print("Valor inicial de c:", c)
c += 5  # c = c + 5
print("Después de c += 5:", c)
c -= 3  # c = c - 3
print("Después de c -= 3:", c)
c *= 2  # c = c * 2
print("Después de c *= 2:", c)
c /= 4  # c = c / 4
print("Después de c /= 4:", c)
c %= 3  # c = c % 3
print("Después de c %= 3:", c)
print()

# Operadores de Membresía (también útiles para verificar la presencia de elementos en colecciones)
lista = [1, 2, 3, 4, 5]
print("2 en lista:", 2 in lista)      # Verifica si 2 está en la lista
print("6 en lista:", 6 in lista)      # Verifica si 6 está en la lista
print("3 no en lista:", 3 not in lista) # Verifica si 3 no está en la lista
print("7 no en lista:", 7 not in lista) # Verifica si 7 no está en la lista
print()



